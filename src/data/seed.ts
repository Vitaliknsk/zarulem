export function generateSeedReports(): Report[] {
  const reports: Report[] = [];
  const managers = seedUsers.filter(u => u.role === 'manager');
  const statuses: ('APPROVED' | 'SUBMITTED' | 'REJECTED' | 'DRAFT')[] = ['APPROVED', 'APPROVED', 'APPROVED', 'SUBMITTED', 'REJECTED', 'DRAFT'];
  
  const now = new Date();
  
  managers.forEach(manager => {
    // Генерируем отчёты за последние 20 дней
    for (let i = 1; i <= 20; i++) {
      const date = new Date(now);
      date.setDate(date.getDate() - i);
      
      // Пропускаем выходные
      if (date.getDay() === 0 || date.getDay() === 6) continue;
      
      const dateStr = date.toISOString().split('T')[0];
      const statusIdx = i <= 2 ? 3 : (i <= 4 ? 4 : (i === 5 ? 5 : 0)); // последние - SUBMITTED/REJECTED/DRAFT
      
      reports.push({
        id: `report-${manager.id}-${dateStr}`,
        userId: manager.id,
        branchId: manager.branchId,
        date: dateStr,
        data: generateReportData(),
        status: statuses[statusIdx],
        createdAt: date.toISOString(),
        updatedAt: date.toISOString(),
        rejectionComment: statuses[statusIdx] === 'REJECTED' ? 'Проверьте данные по каналу Tilda' : undefined,
      });
    }
  });
  
  return reports;
}

